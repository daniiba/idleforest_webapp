CREATE TABLE IF NOT EXISTS public.acquisition_attributions (
    id UUID PRIMARY KEY,
    user_id UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    gclid TEXT,
    gbraid TEXT,
    wbraid TEXT,
    utm_source TEXT,
    utm_medium TEXT,
    utm_campaign TEXT,
    utm_term TEXT,
    utm_content TEXT,
    campaign_id TEXT,
    ad_group_id TEXT,
    creative_id TEXT,
    device TEXT,
    network TEXT,
    match_type TEXT,
    landing_path TEXT,
    referrer TEXT,
    user_agent TEXT,
    intended_platform TEXT CHECK (intended_platform IS NULL OR intended_platform IN ('win32', 'darwin')),
    download_clicked_at TIMESTAMPTZ,
    node_identifier TEXT,
    node_platform TEXT CHECK (node_platform IS NULL OR node_platform IN ('win32', 'darwin')),
    node_connected_at TIMESTAMPTZ,
    node_baseline_requests BIGINT NOT NULL DEFAULT 0,
    first_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS acquisition_attributions_gclid_idx
    ON public.acquisition_attributions(gclid)
    WHERE gclid IS NOT NULL;
CREATE INDEX IF NOT EXISTS acquisition_attributions_user_id_idx
    ON public.acquisition_attributions(user_id)
    WHERE user_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS acquisition_attributions_node_identifier_idx
    ON public.acquisition_attributions(node_identifier)
    WHERE node_identifier IS NOT NULL;
CREATE INDEX IF NOT EXISTS acquisition_attributions_campaign_id_idx
    ON public.acquisition_attributions(campaign_id, first_seen_at DESC);

CREATE TABLE IF NOT EXISTS public.acquisition_node_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribution_id UUID NOT NULL REFERENCES public.acquisition_attributions(id) ON DELETE CASCADE,
    node_identifier TEXT NOT NULL,
    snapshot_date DATE NOT NULL DEFAULT CURRENT_DATE,
    total_requests BIGINT NOT NULL DEFAULT 0,
    opt_in BOOLEAN,
    captured_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (attribution_id, snapshot_date)
);

CREATE INDEX IF NOT EXISTS acquisition_node_snapshots_lookup_idx
    ON public.acquisition_node_snapshots(attribution_id, snapshot_date);

CREATE TABLE IF NOT EXISTS public.acquisition_retention_milestones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribution_id UUID NOT NULL REFERENCES public.acquisition_attributions(id) ON DELETE CASCADE,
    milestone_days SMALLINT NOT NULL CHECK (milestone_days IN (14, 30, 90)),
    active BOOLEAN NOT NULL,
    requests_in_lookback BIGINT NOT NULL DEFAULT 0,
    requests_since_install BIGINT NOT NULL DEFAULT 0,
    evaluated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (attribution_id, milestone_days)
);

CREATE TABLE IF NOT EXISTS public.acquisition_conversions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attribution_id UUID NOT NULL REFERENCES public.acquisition_attributions(id) ON DELETE CASCADE,
    milestone TEXT NOT NULL CHECK (milestone IN ('desktop_node_connected', 'active_14d', 'active_30d')),
    conversion_at TIMESTAMPTZ NOT NULL,
    conversion_value NUMERIC(12, 6) NOT NULL DEFAULT 0,
    currency TEXT NOT NULL DEFAULT 'EUR',
    order_id TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (attribution_id, milestone),
    UNIQUE (order_id)
);

CREATE TABLE IF NOT EXISTS public.acquisition_campaign_costs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cost_date DATE NOT NULL,
    campaign_id TEXT NOT NULL,
    ad_group_id TEXT NOT NULL DEFAULT '',
    cost NUMERIC(12, 4) NOT NULL CHECK (cost >= 0),
    currency TEXT NOT NULL DEFAULT 'EUR',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (cost_date, campaign_id, ad_group_id, currency)
);

