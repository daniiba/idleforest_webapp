-- These tables intentionally have no client policies. Reads and writes go through
-- authenticated server routes using the service role because click IDs are sensitive.

CREATE OR REPLACE VIEW public.acquisition_campaign_performance AS
WITH attribution_rollup AS (
    SELECT
        COALESCE(a.campaign_id, a.utm_campaign, '(unassigned)') AS campaign_key,
        MAX(a.utm_campaign) AS campaign_name,
        COUNT(*) AS attributed_visits,
        COUNT(*) FILTER (WHERE a.download_clicked_at IS NOT NULL) AS downloads,
        COUNT(*) FILTER (WHERE a.node_connected_at IS NOT NULL) AS desktop_nodes,
        COUNT(r14.id) AS evaluated_14d,
        COUNT(r30.id) AS evaluated_30d,
        COUNT(r90.id) AS evaluated_90d,
        COUNT(*) FILTER (WHERE r14.active) AS active_14d,
        COUNT(*) FILTER (WHERE r30.active) AS active_30d,
        COUNT(*) FILTER (WHERE r90.active) AS active_90d,
        COALESCE(SUM(r14.requests_since_install), 0) AS requests_14d,
        COALESCE(SUM(r30.requests_since_install), 0) AS requests_30d,
        COALESCE(SUM(r90.requests_since_install), 0) AS requests_90d
    FROM public.acquisition_attributions a
    LEFT JOIN public.acquisition_retention_milestones r14
        ON r14.attribution_id = a.id AND r14.milestone_days = 14
    LEFT JOIN public.acquisition_retention_milestones r30
        ON r30.attribution_id = a.id AND r30.milestone_days = 30
    LEFT JOIN public.acquisition_retention_milestones r90
        ON r90.attribution_id = a.id AND r90.milestone_days = 90
    GROUP BY COALESCE(a.campaign_id, a.utm_campaign, '(unassigned)')
),
cost_rollup AS (
    SELECT campaign_id AS campaign_key, SUM(cost) AS spend, MAX(currency) AS currency
    FROM public.acquisition_campaign_costs
    GROUP BY campaign_id
)
SELECT
    a.*,
    COALESCE(c.spend, 0) AS spend,
    COALESCE(c.currency, 'EUR') AS currency,
    CASE WHEN a.desktop_nodes > 0 THEN COALESCE(c.spend, 0) / a.desktop_nodes ELSE NULL END AS desktop_node_cac,
    CASE WHEN a.evaluated_14d > 0 THEN (a.requests_14d / 1000.0 * 0.27) / a.evaluated_14d ELSE NULL END AS gross_ltv_14d_eur,
    CASE WHEN a.evaluated_30d > 0 THEN (a.requests_30d / 1000.0 * 0.27) / a.evaluated_30d ELSE NULL END AS gross_ltv_30d_eur,
    CASE WHEN a.evaluated_90d > 0 THEN (a.requests_90d / 1000.0 * 0.27) / a.evaluated_90d ELSE NULL END AS gross_ltv_90d_eur
FROM attribution_rollup a
LEFT JOIN cost_rollup c USING (campaign_key);

COMMENT ON VIEW public.acquisition_campaign_performance IS
    'Paid acquisition funnel and gross request-value proxy by campaign. The 0.27 EUR/1k request rate must be updated if realized monetization changes.';

